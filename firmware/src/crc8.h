#pragma once
#include <stdint.h>
#include <stddef.h>

// CRC-8 with polynomial 0x07 (covers TYPE + LEN + PAYLOAD)
static inline uint8_t crc8(const uint8_t *data, size_t len) {
    uint8_t crc = 0x00;
    for (size_t i = 0; i < len; i++) {
        crc ^= data[i];
        for (int bit = 0; bit < 8; bit++) {
            crc = (crc & 0x80) ? ((crc << 1) ^ 0x07) : (crc << 1);
        }
    }
    return crc;
}
